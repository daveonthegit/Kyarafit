import type { VaultDoc, VaultDocCodec } from "./store";

/**
 * Photo references inside vault documents.
 *
 * Picked photos are copied into the vault's own directory (`<documents>/vaults/<vaultKey>/images/`)
 * before any entity references them, so they survive restarts and never depend on a picker cache or
 * a network upload. Absolute `file://` paths are NOT stable on iOS (the app container path can change
 * across updates/restores) and are meaningless on another device, so the stored/exported form of a
 * document uses a portable token, `kyarafit-image:<imageKey>`. The store's codec resolves tokens to
 * the current on-device path when documents are loaded and converts them back on write, so screens
 * keep rendering `imageUrl` as an ordinary URI.
 */

export const VAULT_IMAGE_TOKEN = "kyarafit-image:";

/** Image keys are generated by the app (`img_<uuid>`) — keep the accepted alphabet strict. */
const IMAGE_KEY = "[A-Za-z0-9_-]+";
const VAULT_PATH_RE = new RegExp(`^file://.*/vaults/[^/]+/images/(${IMAGE_KEY})$`);
const LEGACY_PATH_RE = new RegExp(`^file://.*/local-images/(${IMAGE_KEY})$`);
const TOKEN_RE = new RegExp(`^${VAULT_IMAGE_TOKEN}(${IMAGE_KEY})$`);

export function vaultImageDir(documentDirectory: string, vaultKey: string): string {
  return `${documentDirectory}vaults/${vaultKey}/images/`;
}

/** The image key a stored or device value refers to, or null when it is not a vault photo. */
export function vaultImageKey(value: string): string | null {
  return (
    TOKEN_RE.exec(value)?.[1] ??
    VAULT_PATH_RE.exec(value)?.[1] ??
    LEGACY_PATH_RE.exec(value)?.[1] ??
    null
  );
}

export function isVaultImageValue(value: unknown): value is string {
  return typeof value === "string" && vaultImageKey(value) !== null;
}

function mapStrings(value: unknown, fn: (s: string) => string): unknown {
  if (typeof value === "string") return fn(value);
  if (Array.isArray(value)) {
    let changed = false;
    const out = value.map((item) => {
      const next = mapStrings(item, fn);
      if (next !== item) changed = true;
      return next;
    });
    return changed ? out : value;
  }
  if (value !== null && typeof value === "object") {
    let changed = false;
    const out: Record<string, unknown> = {};
    for (const [key, item] of Object.entries(value as Record<string, unknown>)) {
      const next = mapStrings(item, fn);
      if (next !== item) changed = true;
      out[key] = next;
    }
    return changed ? out : value;
  }
  return value;
}

/** Replace device paths of vault photos with portable tokens (deep). */
export function toPortableImageRefs<T>(value: T): T {
  return mapStrings(value, (s) => {
    if (!s.startsWith("file://")) return s;
    const key = vaultImageKey(s);
    return key ? `${VAULT_IMAGE_TOKEN}${key}` : s;
  }) as T;
}

/** Resolve portable tokens to the current device path inside `imageDir` (deep). */
export function toDeviceImageRefs<T>(value: T, imageDir: string): T {
  return mapStrings(value, (s) => {
    const key = TOKEN_RE.exec(s)?.[1];
    return key ? `${imageDir}${key}` : s;
  }) as T;
}

export interface VaultPhotoReference {
  key: string;
  storageId?: string;
}

function recordPhoto(record: Record<string, unknown>): VaultPhotoReference | null {
  if (record.kind === "local" || record.kind === "cloud") {
    if (typeof record.imageKey !== "string" || !new RegExp(`^${IMAGE_KEY}$`).test(record.imageKey))
      return null;
    return {
      key: record.imageKey,
      ...(record.kind === "cloud" && typeof record.storageId === "string"
        ? { storageId: record.storageId }
        : {}),
    };
  }
  if (typeof record.imageStorageId !== "string" || !record.imageStorageId) return null;
  const localKey = typeof record.imageUrl === "string" ? vaultImageKey(record.imageUrl) : null;
  const key =
    localKey ??
    `cloud_${Array.from(record.imageStorageId, (character) => character.codePointAt(0)!.toString(16).padStart(6, "0")).join("")}`;
  return { key, storageId: record.imageStorageId };
}

export function collectVaultPhotos(
  value: unknown,
  into = new Map<string, VaultPhotoReference>()
): Map<string, VaultPhotoReference> {
  if (typeof value === "string") {
    const key = vaultImageKey(value);
    if (key && !into.has(key)) into.set(key, { key });
  } else if (Array.isArray(value)) {
    for (const item of value) collectVaultPhotos(item, into);
  } else if (value !== null && typeof value === "object") {
    const record = value as Record<string, unknown>;
    const photo = recordPhoto(record);
    if (photo) into.set(photo.key, { ...into.get(photo.key), ...photo });
    for (const item of Object.values(record)) collectVaultPhotos(item, into);
  }
  return into;
}

export function collectVaultImageKeys(value: unknown, into = new Set<string>()): Set<string> {
  for (const key of collectVaultPhotos(value).keys()) into.add(key);
  return into;
}

export function localizeVaultPhotos<T>(value: T, available: ReadonlySet<string>): T {
  if (Array.isArray(value))
    return value.map((item) => localizeVaultPhotos(item, available)) as unknown as T;
  if (value === null || typeof value !== "object") return value;
  const record = value as Record<string, unknown>;
  const photo = recordPhoto(record);
  if (photo?.storageId && available.has(photo.key) && record.kind === "cloud") {
    return {
      kind: "local",
      imageKey: photo.key,
      uri: `${VAULT_IMAGE_TOKEN}${photo.key}`,
    } as unknown as T;
  }
  const result = Object.fromEntries(
    Object.entries(record).map(([key, item]) => [key, localizeVaultPhotos(item, available)])
  );
  if (photo?.storageId && available.has(photo.key) && typeof record.imageStorageId === "string") {
    delete result.imageStorageId;
    result.imageUrl = `${VAULT_IMAGE_TOKEN}${photo.key}`;
  }
  return result as unknown as T;
}

export function vaultImageCodec(imageDir: string): VaultDocCodec {
  return {
    toStored: (doc: VaultDoc) => toPortableImageRefs(doc),
    fromStored: (doc: VaultDoc) => toDeviceImageRefs(doc, imageDir),
  };
}
